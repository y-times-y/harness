/**
 * Claude Code: `~/.claude/projects/<cwd with every non-alphanumeric char as "-">/<session id>.jsonl`.
 *
 * Shapes handled (one JSON record per line):
 * - 1.x / 2.0 (agent-hop era): `user` / `assistant` records with `message.content` as a
 *   string or Anthropic content blocks (`text`, `tool_use`, `tool_result`), `summary`
 *   title records, `isSidechain` subagent records inline in the same file.
 * - 2.1.x (verified on 2.1.296): the same core records, one content block per assistant
 *   line, plus `ai-title` / `custom-title` / `last-prompt` / `attachment` / `system`
 *   bookkeeping records (skipped), `origin` / `promptSource` on user records, `isMeta`
 *   injected user records, `isCompactSummary` compaction summaries after a
 *   `compact_boundary`, `toolUseResult` with stdout/stderr and `bashEditDiff`, and
 *   subagent transcripts moved to `<session id>/subagents/*.jsonl` (not read here).
 *
 * Exit codes: Claude Code records none. A failed Bash result is `is_error: true` with
 * text starting "Exit code N"; a successful one is `is_error: false` without a
 * `returnCodeInterpretation` (that field marks a benign non-zero exit such as grep's 1),
 * which is read as exit code 0.
 */
import os from "node:os";
import path from "node:path";
import {
	asArray,
	asObject,
	asString,
	canonicalPath,
	fileMtimeMs,
	isPathInside,
	type JsonObject,
	linesForward,
	listDirectory,
	parseJsonObject,
} from "./io.ts";
import {
	createToolCall,
	exitCodeFromText,
	MAX_TOOL_INPUT_CHARS,
	MAX_TOOL_OUTPUT_CHARS,
	setToolOutput,
} from "./tool-calls.ts";
import {
	approximateTextChars,
	type TranscriptScan,
	TurnAssembler,
	titleFromPrompt,
	transcriptReadMode,
	visitTranscriptRecords,
} from "./transcript.ts";
import type { LocalSession, ReaderOptions, SessionRef } from "./types.ts";

const HEAD_SCAN_LINES = 40;
const MAX_FILES_VERIFIED_PER_DIRECTORY = 5;

const INJECTED_USER_TEXT_PREFIXES = [
	"<local-command-caveat>",
	"<local-command-stdout>",
	"<local-command-stderr>",
	"<command-name>",
	"<command-message>",
	"<command-args>",
	"<task-notification>",
	"<system-reminder>",
	"<bash-stdout>",
	"<bash-stderr>",
	"[Request interrupted by user",
	"Caveat: The messages below were generated by the user while running local commands",
];

export function claudeProjectsDirectory(home = os.homedir()): string {
	return path.join(home, ".claude", "projects");
}

export function encodeClaudeProjectDirectory(cwd: string): string {
	return cwd.replace(/[^A-Za-z0-9]/g, "-");
}

/** Reads `"cwd":"..."` from the first lines of a transcript without parsing whole records. */
export function claudeSessionCwd(file: string): string | undefined {
	let scanned = 0;
	for (const line of linesForward(file, 64 * 1024)) {
		const match = /"cwd":("(?:[^"\\]|\\.)*")/.exec(line);
		if (match?.[1]) {
			try {
				return JSON.parse(match[1]) as string;
			} catch {
				return undefined;
			}
		}
		scanned++;
		if (scanned >= HEAD_SCAN_LINES) return undefined;
	}
	return undefined;
}

/**
 * Newest session per project directory whose recorded cwd is the repo root or
 * inside it. Directory names are a lossy encoding of the cwd, so candidates are
 * picked by name prefix and confirmed from the transcript head.
 */
export function discoverClaudeSessions(
	repoRoot: string,
	home = os.homedir(),
	limit = 1,
): SessionRef[] {
	const root = canonicalPath(repoRoot);
	const encodedRoot = encodeClaudeProjectDirectory(root);
	const projectsDirectory = claudeProjectsDirectory(home);
	const refs: SessionRef[] = [];
	for (const entry of listDirectory(projectsDirectory)) {
		if (!entry.isDirectory()) continue;
		if (entry.name !== encodedRoot && !entry.name.startsWith(`${encodedRoot}-`))
			continue;
		const directory = path.join(projectsDirectory, entry.name);
		const files = listDirectory(directory)
			.filter((file) => file.isFile() && file.name.endsWith(".jsonl"))
			.map((file) => {
				const location = path.join(directory, file.name);
				return {
					location,
					id: file.name.slice(0, -".jsonl".length),
					mtime: fileMtimeMs(location) ?? 0,
				};
			})
			.sort((a, b) => b.mtime - a.mtime)
			.slice(0, Math.max(MAX_FILES_VERIFIED_PER_DIRECTORY, limit));
		let found = 0;
		for (const file of files) {
			const cwd = claudeSessionCwd(file.location);
			if (!cwd || !isPathInside(canonicalPath(cwd), root)) continue;
			refs.push({
				tool: "claude",
				id: file.id,
				cwd,
				updatedAt: file.mtime,
				location: file.location,
			});
			if (++found >= limit) break;
		}
	}
	return refs;
}

const claudeScan: TranscriptScan = {
	mayBeRelevant: (line) =>
		line.includes('"type":"user"') ||
		line.includes('"type":"assistant"') ||
		line.includes('"type":"ai-title"') ||
		line.includes('"type":"custom-title"') ||
		line.includes('"type":"summary"'),
	mayBeCompactionSummary: (line) => line.includes('"isCompactSummary":true'),
	mayHoldToolActivity: (line) =>
		line.includes('"tool_use"') || line.includes('"tool_result"'),
	contentChars: (record) =>
		approximateTextChars(
			asObject(record.message)?.content,
			MAX_TOOL_INPUT_CHARS + MAX_TOOL_OUTPUT_CHARS,
		),
	startsUserTurn: (record) => humanPromptText(record) !== undefined,
	isCompactionSummary: (record) =>
		record.type === "user" && record.isCompactSummary === true,
};

function isInjectedUserText(text: string): boolean {
	const trimmed = text.trimStart();
	return INJECTED_USER_TEXT_PREFIXES.some((prefix) =>
		trimmed.startsWith(prefix),
	);
}

function userBashInput(text: string): string | undefined {
	const match = /^<bash-input>([\s\S]*)<\/bash-input>\s*$/.exec(text.trim());
	return match?.[1]?.trim();
}

/** Text a person typed, or undefined for tool results, injected context and non-human origins. */
export function humanPromptText(record: JsonObject): string | undefined {
	if (
		record.type !== "user" ||
		record.isMeta === true ||
		record.isCompactSummary === true
	)
		return undefined;
	if (record.isSidechain === true) return undefined;
	const originKind = asString(asObject(record.origin)?.kind);
	if (originKind !== undefined && originKind !== "human") return undefined;
	const content = asObject(record.message)?.content;
	const parts: string[] = [];
	if (typeof content === "string") parts.push(content);
	for (const block of asArray(content)) {
		const item = asObject(block);
		if (item?.type === "text" && typeof item.text === "string")
			parts.push(item.text);
	}
	const kept: string[] = [];
	for (const part of parts) {
		const bashInput = userBashInput(part);
		if (bashInput) kept.push(`! ${bashInput}`);
		else if (!isInjectedUserText(part)) kept.push(part);
	}
	const text = kept.join("\n\n").trim();
	return text ? text : undefined;
}

export function toolResultText(content: unknown): string {
	if (typeof content === "string") return content;
	return asArray(content)
		.map((item) => asObject(item))
		.filter((item) => item?.type === "text" && typeof item.text === "string")
		.map((item) => item?.text as string)
		.join("\n");
}

function applyToolResult(
	assembler: TurnAssembler,
	block: JsonObject,
	toolUseResult: unknown,
): void {
	const call = assembler.toolCall(asString(block.tool_use_id));
	if (!call) return;
	const output = toolResultText(block.content);
	setToolOutput(call, output);
	const isError = block.is_error === true;
	if (block.is_error !== undefined) call.isError = isError;
	const result = asObject(toolUseResult);
	if (call.kind === "shell") {
		const exitCode = exitCodeFromText(isError ? output : undefined);
		if (exitCode !== undefined) call.exitCode = exitCode;
		else if (
			block.is_error === false &&
			result &&
			result.interrupted !== true &&
			result.returnCodeInterpretation === undefined &&
			result.backgroundTaskId === undefined
		) {
			call.exitCode = 0;
		}
	}
	for (const changed of asArray(asObject(result?.bashEditDiff)?.changedFiles)) {
		if (typeof changed === "string" && !call.changedPaths.includes(changed))
			call.changedPaths.push(changed);
	}
	assembler.resultApplied(call);
}

function firstHumanPromptInHead(file: string): {
	text?: string;
	timestamp?: string;
} {
	let scanned = 0;
	let timestamp: string | undefined;
	for (const line of linesForward(file, 64 * 1024)) {
		scanned++;
		if (scanned > HEAD_SCAN_LINES * 5) break;
		if (!line.includes('"type":"user"') && timestamp) continue;
		const record = parseJsonObject(line);
		if (!record) continue;
		timestamp ??= asString(record.timestamp);
		const text = humanPromptText(record);
		if (text) return { text, timestamp };
	}
	return { timestamp };
}

export function readClaudeSession(
	ref: SessionRef,
	options: ReaderOptions = {},
): LocalSession {
	const assembler = new TurnAssembler(options.activityOnly);
	const seenBlocks = new Set<string>();
	let cwd = ref.cwd;
	let gitBranch: string | undefined;
	let model: string | undefined;
	let cliVersion: string | undefined;
	let startedAt: string | undefined;
	let customTitle: string | undefined;
	let aiTitle: string | undefined;
	let summaryTitle: string | undefined;
	let firstPrompt: string | undefined;

	const visit = (record: JsonObject): void => {
		if (record.type === "custom-title")
			customTitle = asString(record.customTitle) ?? customTitle;
		if (record.type === "ai-title")
			aiTitle = asString(record.aiTitle) ?? aiTitle;
		if (record.type === "summary")
			summaryTitle = asString(record.summary) ?? summaryTitle;
		if (record.type !== "user" && record.type !== "assistant") return;
		if (record.isSidechain === true) return;
		const at = asString(record.timestamp);
		startedAt ??= at;
		cwd = asString(record.cwd) ?? cwd;
		gitBranch = asString(record.gitBranch) || gitBranch;
		cliVersion = asString(record.version) ?? cliVersion;
		const message = asObject(record.message);

		if (record.type === "assistant") {
			const messageModel = asString(message?.model);
			if (record.isApiErrorMessage === true || messageModel === "<synthetic>")
				return;
			model = messageModel ?? model;
			const messageId = asString(message?.id) ?? asString(record.uuid) ?? "";
			const content = message?.content;
			if (typeof content === "string") assembler.addAssistantText(content, at);
			for (const [index, raw] of asArray(content).entries()) {
				const block = asObject(raw);
				if (!block) continue;
				const blockKey = `${messageId}:${asString(block.id) ?? `${index}:${asString(block.text)?.slice(0, 200)}`}`;
				if (seenBlocks.has(blockKey)) continue;
				seenBlocks.add(blockKey);
				if (block.type === "text")
					assembler.addAssistantText(asString(block.text) ?? "", at);
				if (block.type === "tool_use") {
					const call = createToolCall({
						name: asString(block.name) ?? "unknown_tool",
						input: block.input ?? {},
					});
					assembler.addToolCall(call, asString(block.id), at);
				}
			}
			return;
		}

		if (record.isCompactSummary === true) {
			const content = message?.content;
			assembler.addCompactionSummary(
				typeof content === "string" ? content : toolResultText(content),
				at,
			);
			return;
		}
		for (const raw of asArray(message?.content)) {
			const block = asObject(raw);
			if (block?.type === "tool_result")
				applyToolResult(assembler, block, record.toolUseResult);
		}
		const prompt = humanPromptText(record);
		if (prompt) {
			firstPrompt ??= prompt;
			assembler.addUserText(prompt, at);
		}
	};
	const { readFromStart, parseErrors } = visitTranscriptRecords(
		ref.location,
		claudeScan,
		transcriptReadMode(options),
		visit,
	);

	if (!readFromStart) {
		const head = firstHumanPromptInHead(ref.location);
		startedAt = head.timestamp ?? startedAt;
		firstPrompt = head.text ?? firstPrompt;
	}

	return {
		tool: "claude",
		id: ref.id,
		cwd,
		gitBranch,
		model,
		startedAt,
		updatedAt: ref.updatedAt,
		title:
			customTitle ?? aiTitle ?? summaryTitle ?? titleFromPrompt(firstPrompt),
		cliVersion,
		turns: assembler.finish(),
		readFromStart,
		unparsedRecords: parseErrors,
	};
}

export function claudeSessionRefForFile(file: string): SessionRef | undefined {
	const cwd = claudeSessionCwd(file);
	if (!cwd) return undefined;
	return {
		tool: "claude",
		id: path.basename(file, ".jsonl"),
		cwd,
		updatedAt: fileMtimeMs(file) ?? 0,
		location: file,
	};
}
